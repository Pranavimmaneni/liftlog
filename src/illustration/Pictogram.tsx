import { useEffect, useRef, useState } from 'react';
import { poseDef } from './svg';
import { layersFor } from './tier1';
import { C } from './rig';
import { muscleMapBody } from './muscles';
import type { Exercise } from '@/engine/types';

const LOOP_MS = 1600;

function prefersReducedMotion(): boolean {
  return typeof window !== 'undefined' && !!window.matchMedia?.('(prefers-reduced-motion: reduce)').matches;
}

/** Ease-in-out ping-pong over one 1.6 s loop (FR-ILL-4). */
export function phase(ms: number): number {
  const p = (ms % LOOP_MS) / LOOP_MS;
  const x = p < 0.5 ? p * 2 : 2 - p * 2;
  return x < 0.5 ? 2 * x * x : 1 - (-2 * x + 2) ** 2 / 2;
}

/** ~30 fps is smooth for a 1.6 s loop and halves the work on phones. */
const FRAME_MS = 33;

/**
 * FR-ILL-1: `<Pictogram poseId variant="full|thumb" animate?>`. The markup is generated by the
 * pictos.py port (trusted, token-coloured), so it is injected as SVG children. When animating, only
 * the solid figure layer is redrawn; the equipment, ghost and arrow stay put.
 */
export function Pictogram({
  poseId,
  variant = 'full',
  animate = false,
  label,
  className = '',
}: {
  poseId: string;
  variant?: 'full' | 'thumb';
  animate?: boolean;
  label: string;
  className?: string;
}) {
  const solidRef = useRef<SVGGElement>(null);
  const [layers] = useState(() => {
    const def = poseDef(poseId);
    if (!def) return null;
    const l = layersFor(def);
    return variant === 'thumb' ? { back: l.back, ghost: '', solid: l.solid, arrow: '' } : l;
  });

  useEffect(() => {
    const def = poseDef(poseId);
    if (!animate || variant !== 'full' || prefersReducedMotion() || !def) return;
    let raf = 0;
    let last = 0;
    const start = performance.now();
    const tick = (now: number) => {
      if (now - last >= FRAME_MS && solidRef.current) {
        last = now;
        solidRef.current.innerHTML = layersFor(def, C.PANEL_BG, phase(now - start)).solid;
      }
      raf = requestAnimationFrame(tick);
    };
    raf = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(raf);
  }, [animate, variant, poseId]);

  return (
    <svg viewBox="0 0 240 170" fill="none" role="img" aria-label={label} className={className}>
      {layers && (
        <>
          <g dangerouslySetInnerHTML={{ __html: layers.back + layers.ghost }} />
          <g ref={solidRef} dangerouslySetInnerHTML={{ __html: layers.solid }} />
          <g dangerouslySetInnerHTML={{ __html: layers.arrow }} />
        </>
      )}
    </svg>
  );
}

/** FR-ILL-1: `<MuscleMap primary secondary>` (front + back). */
export function MuscleMap({
  primary,
  secondary,
  label = 'Muscles worked',
  className = '',
}: {
  primary: string[];
  secondary: string[];
  label?: string;
  className?: string;
}) {
  return (
    <svg
      viewBox="0 0 210 170"
      role="img"
      aria-label={label}
      className={className}
      dangerouslySetInnerHTML={{ __html: muscleMapBody(primary, secondary) }}
    />
  );
}

/**
 * Picture for any exercise: its pictogram when a pose exists, otherwise the muscle map
 * (FR-ILL-3). Thumbnails sit on the panel colour like the mockups.
 */
export function ExerciseThumb({
  exercise,
  className = '',
}: {
  exercise: Pick<Exercise, 'name' | 'poseId' | 'primary' | 'secondary'>;
  className?: string;
}) {
  const hasPose = !!poseDef(exercise.poseId);
  return (
    <div
      className={`flex shrink-0 items-center justify-center overflow-hidden rounded bg-panel ${className}`}
      aria-hidden="true"
    >
      {hasPose ? (
        <Pictogram
          poseId={exercise.poseId!}
          variant="thumb"
          label={exercise.name}
          className="h-full w-full"
        />
      ) : (
        <MuscleMap primary={exercise.primary} secondary={exercise.secondary} className="h-[88%] w-[88%]" />
      )}
    </div>
  );
}
