import { useEffect, useRef, useState } from 'react';
import { illustrationBody, poseDef } from './svg';
import { muscleMapBody } from './muscles';
import type { Exercise } from '@/engine/types';

const LOOP_MS = 1600;

function prefersReducedMotion(): boolean {
  return typeof window !== 'undefined' && !!window.matchMedia?.('(prefers-reduced-motion: reduce)').matches;
}

/** Ease-in-out ping-pong over one 1.6 s loop (FR-ILL-4). */
export function phase(ms: number): number {
  const p = (ms % LOOP_MS) / LOOP_MS;
  const x = p < 0.5 ? p * 2 : 2 - p * 2;
  return x < 0.5 ? 2 * x * x : 1 - (-2 * x + 2) ** 2 / 2;
}

/**
 * FR-ILL-1: `<Pictogram poseId variant="full|thumb" animate?>`. The markup is generated by the
 * pictos.py port (trusted, token-coloured), so it is injected as SVG children.
 */
export function Pictogram({
  poseId,
  variant = 'full',
  animate = false,
  label,
  className = '',
}: {
  poseId: string;
  variant?: 'full' | 'thumb';
  animate?: boolean;
  label: string;
  className?: string;
}) {
  const ref = useRef<SVGSVGElement>(null);
  const [staticBody] = useState(() =>
    variant === 'thumb' ? illustrationBody(poseId, { ghost: false, arrow: false }) : illustrationBody(poseId),
  );

  useEffect(() => {
    if (!animate || variant !== 'full' || prefersReducedMotion() || !poseDef(poseId)) return;
    let raf = 0;
    const start = performance.now();
    const tick = (now: number) => {
      if (ref.current) ref.current.innerHTML = illustrationBody(poseId, { t: phase(now - start) });
      raf = requestAnimationFrame(tick);
    };
    raf = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(raf);
  }, [animate, variant, poseId]);

  return (
    <svg
      ref={ref}
      viewBox="0 0 240 170"
      fill="none"
      role="img"
      aria-label={label}
      className={className}
      dangerouslySetInnerHTML={{ __html: staticBody }}
    />
  );
}

/** FR-ILL-1: `<MuscleMap primary secondary>` (front + back). */
export function MuscleMap({
  primary,
  secondary,
  label = 'Muscles worked',
  className = '',
}: {
  primary: string[];
  secondary: string[];
  label?: string;
  className?: string;
}) {
  return (
    <svg
      viewBox="0 0 210 170"
      role="img"
      aria-label={label}
      className={className}
      dangerouslySetInnerHTML={{ __html: muscleMapBody(primary, secondary) }}
    />
  );
}

/**
 * Picture for any exercise: its pictogram when a pose exists, otherwise the muscle map
 * (FR-ILL-3). Thumbnails sit on the panel colour like the mockups.
 */
export function ExerciseThumb({
  exercise,
  className = '',
}: {
  exercise: Pick<Exercise, 'name' | 'poseId' | 'primary' | 'secondary'>;
  className?: string;
}) {
  const hasPose = !!poseDef(exercise.poseId);
  return (
    <div
      className={`flex shrink-0 items-center justify-center overflow-hidden rounded bg-panel ${className}`}
      aria-hidden="true"
    >
      {hasPose ? (
        <Pictogram
          poseId={exercise.poseId!}
          variant="thumb"
          label={exercise.name}
          className="h-full w-full"
        />
      ) : (
        <MuscleMap primary={exercise.primary} secondary={exercise.secondary} className="h-[88%] w-[88%]" />
      )}
    </div>
  );
}
